local P=dofile('diagnostics_protocol.lua')
local pos={x=0,y=170,z=0}
local pose={position=pos,orientation={x=0,y=0,z=0,w=1}}
local v={x=3,y=4,z=0}
local w={x=0,y=0,z=0}
local p=P.frame('LAB','session-a',0,.1,pose,v,w)
assert(P.validate(p,'LAB'))
assert(P.speed(v)==5)
assert(p.status=='ok' and p.seq==0)
local s=P.newState('LAB')
assert(P.health(s,0,3)=='no_data')
assert(P.accept(s,p,1))
assert(P.health(s,3,3)=='ok')
assert(P.health(s,4.01,3)=='stale')
local ok,why=P.accept(s,p,4.1)
assert(not ok and why=='out_of_order')
local p2=P.frame('LAB','session-a',1,.2,pose,v,w)
assert(P.accept(s,p2,5))
local forged=P.frame('LAB','session-a',2,.3,pose,v,w)
forged.command='start'
ok,why=P.accept(s,forged,5.1)
assert(not ok and why=='commands_not_supported')
local nan=P.frame('LAB','session-a',2,.3,pose,v,w)
nan.pos={x=0/0,y=0,z=0}
ok,why=P.accept(s,nan,5.2)
assert(not ok and why=='sensor_fields')
local other=P.frame('OTHER','session-a',2,.3,pose,v,w)
ok,why=P.accept(s,other,5.3)
assert(not ok and why=='vehicle')
local outOfOrder=P.frame('LAB','session-a',2,.1,pose,v,w)
ok,why=P.accept(s,outOfOrder,5.4)
assert(not ok and why=='out_of_order')
local restart=P.frame('LAB','session-b',0,0,pose,v,w)
ok,why=P.accept(s,restart,5.5)
assert(not ok and why=='session_conflict')
assert(P.accept(s,restart,16))
local bad=P.frame('LAB','session-b',1,.1,nil,nil,nil)
assert(bad.status=='sensor_error' and not bad.pos)
assert(P.accept(s,bad,17))
assert(P.health(s,17.1,3)=='sensor_error')
local q=P.frame('LAB','session-b',2,.2,pose,v,w)
q.orientation={x=0,y=0,z=0,w=0}
ok,why=P.accept(s,q,17.2)
assert(not ok and why=='sensor_fields')
assert(s.accepted==4 and s.rejected==7)
print('OSPREY read-only diagnostic protocol tests passed')
