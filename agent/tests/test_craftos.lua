-- EN: Execute actual Lua programs against deterministic simulated CraftOS globals.
-- RU: Запуск Lua-программ с подменой системных API на тестовые.
local Engine=require("agent.sim.engine")
local CC=require("agent.sim.cc")
local Runtime=require("agent.sim.craftos")
local e=Engine.new({gravity={x=0,y=0,z=0}})
local body=e.world:addBody({position={x=1,y=2,z=3}})
local node=CC.new(e):addComputer(3,body)
local program=[[
assert(sublevel.isInPlotGrid())
local pose=sublevel.getLogicalPose()
assert(pose.position.x==1 and pose.position.z==3)
redstone.setAnalogOutput("back",13)
assert(redstone.getAnalogOutput("back")==13)
os.queueEvent("custom",4)
local ev,n=os.pullEvent("custom")
assert(ev=="custom" and n==4)
sleep(0.1)
assert(os.clock()>0)
print("ok",os.clock())
]]
local result=Runtime.run(e,node,program)
assert(result.ok,result.error)
assert(result.output[1]:find("ok"))
assert(e.tick==2)
local failed=Runtime.run(e,node,"while true do end",{instructions=20000})
assert(not failed.ok and failed.error:find("budget exceeded"))
local blocked=Runtime.run(e,node,'io.open("/etc/passwd")')
assert(not blocked.ok)
print("simulated CraftOS program tests passed")
