-- EN: Unit tests verify the mocks, not in-game equivalence.
-- RU: Тесты проверяют имитации, а не их идентичность игре.
local Peripheral = require('agent.mocks.peripheral')
local Clock = require('agent.mocks.clock')
local Bus = require('agent.mocks.rednet')
local Sublevel = require('agent.mocks.sublevel')
local Redstone = require('agent.mocks.redstone')

local p = Peripheral.new()
p:attach('left', 'monitor', {getSize=function() return 20, 10 end})
local api = p:api()
assert(api.getType('left') == 'monitor')
assert(api.isPresent('left'))
assert(api.wrap('left').getSize() == 20)
assert(api.find('monitor').getSize() == 20)
assert(#api.getMethods('left') == 1)
p:detach('left')
assert(not api.isPresent('left') and api.wrap('left') == nil)
assert(not pcall(api.call, 'left', 'getSize'))

local timer = Clock.new()
local ta = timer:api()
local id = ta.startTimer(0.2)
timer:advance(0.1)
assert(#timer.events == 0)
timer:advance(0.1)
local event, n = ta.pullEvent()
assert(event == 'timer' and n == id)
assert(not pcall(ta.pullEvent))

local network = Bus.new()
local sender = network:node(1)
local receiver = network:node(2)
sender.open('left')
receiver.open('right')
assert(sender.send(2,{status='ok'},'sample'))
local from, body, protocol = receiver.receive('sample')
assert(from == 1 and body.status == 'ok' and protocol == 'sample')
network.dropNext = true
assert(sender.send(2,'lost','sample') == false)
assert(receiver.receive('sample') == nil)

local ship = Sublevel.new()
assert(ship:api().getLogicalPose().position.x == 0)
ship:setVelocity({x=5,y=0,z=0})
assert(ship:api().getVelocity().x == 5)
local returned = ship:api().getVelocity()
returned.x = -100
assert(ship:api().getVelocity().x == 5)

local redstone = Redstone.new()
local rs = redstone:api()
rs.setOutput('back',true)
rs.setAnalogOutput('top',15)
assert(rs.getOutput('back') and rs.getAnalogOutput('top')==15)
assert(not pcall(rs.setAnalogOutput,'top',16))
print('mock tests passed')
